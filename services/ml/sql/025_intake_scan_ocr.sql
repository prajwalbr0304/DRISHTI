CREATE INDEX IF NOT EXISTS "idx_intakescanfield_review"
    ON "IntakeScanField" ("IntakeScanID") WHERE "RequiresReview";

CREATE INDEX IF NOT EXISTS "gin_intakescan_payload"
    ON "IntakeScan" USING GIN ("ExtractedPayload");
CREATE INDEX IF NOT EXISTS "gin_intakescan_fieldconf"
    ON "IntakeScan" USING GIN ("FieldConfidence");

-- =============================================================================
-- 6. TRIGGERS (updated_at maintenance — reuse shared fn_set_updated_at())
-- =============================================================================
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_proc WHERE proname = 'fn_set_updated_at')
       AND NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'trg_intakescan_updated') THEN
        CREATE TRIGGER "trg_intakescan_updated" BEFORE UPDATE ON "IntakeScan"
            FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();
    END IF;
END$$;

-- =============================================================================
-- 7. REVIEW QUEUE VIEW — scans awaiting officer confirmation.
--    Drives the admin "extraction queue" panel, which until now honestly
--    reported that no extraction queue existed.
-- =============================================================================
CREATE OR REPLACE VIEW "vw_intake_scan_queue" AS
SELECT
    s."IntakeScanID",
    s."ScanKey",
    s."Status",
    s."ReviewState",
    s."DetectedLanguage",
    s."OcrConfidence",
    s."TemplateCode",
    s."TemplateMatched",
    s."FileName",
    s."MimeType",
    s."SizeBytes",
    s."CreatedByActor",
    s."CreatedAt",
    s."OcrFinishedAt",
    d."DraftKey",
    d."Status" AS "DraftStatus",
    d."CaseKind",
    d."CaseMasterID",
    (SELECT count(*) FROM "IntakeScanField" f
      WHERE f."IntakeScanID" = s."IntakeScanID")                       AS "FieldCount",
    (SELECT count(*) FROM "IntakeScanField" f
      WHERE f."IntakeScanID" = s."IntakeScanID" AND f."RequiresReview") AS "FieldsNeedingReview",
    (SELECT count(*) FROM "IntakeScanField" f
      WHERE f."IntakeScanID" = s."IntakeScanID" AND f."WasEdited")      AS "FieldsEdited",
    jsonb_array_length(s."UnresolvedFields")                           AS "UnresolvedCount"
FROM "IntakeScan" s
LEFT JOIN "IntakeDraft" d ON d."IntakeDraftID" = s."IntakeDraftID";
COMMENT ON VIEW "vw_intake_scan_queue" IS
    'Scanned-FIR OCR review queue: one row per scan with its draft, confidence, and the count of fields still needing human confirmation.';

