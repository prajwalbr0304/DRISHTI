-- =============================================================================
-- DRISHTI migration 008 — feature + prediction governance data contract
-- Target: PostgreSQL 15+ / Supabase (live PG 17.6)
-- Depends on: 005, 006, 007
-- =============================================================================
--
-- Builds the governed bridge between verified inputs and any model (roadmap §29):
-- FeatureDefinition -> FeatureSchemaVersion -> immutable FeatureSnapshot ->
-- PredictionRequest -> PredictionResult -> PredictionReview, plus
-- TrainingDatasetSnapshot and leakage-safe OutcomeLabel. Extends ModelVersion
-- with artifact/image digest, dataset/feature-schema, approval, evaluation,
-- environment and rollback metadata (audit found 24/32 versions incomplete).
--
-- Protected/restricted attributes (caste, religion, gender, juvenile status)
-- are recorded with Sensitivity and are BLOCKED from feature schemas by default.
--
-- RLS stays DISABLED + NO FORCE (hackathon). No RLS policies. Additive +
-- idempotent.
-- =============================================================================

BEGIN;

-- =============================================================================
-- 1. FEATURE DEFINITIONS + SCHEMA VERSIONS (Group 11)
-- =============================================================================
CREATE TABLE IF NOT EXISTS "FeatureDefinition" (
    "FeatureDefinitionID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name"          VARCHAR NOT NULL UNIQUE,
    "ValueType"     VARCHAR NOT NULL DEFAULT 'numeric',   -- numeric|categorical|boolean|temporal
    "Description"   TEXT,
    "SourceTable"   VARCHAR,
    "SourceField"   VARCHAR,
    "SourceEvent"   VARCHAR,
    "Transformation" VARCHAR,
    "WindowSpec"    VARCHAR,
    "ObservationCutoffBehavior" VARCHAR NOT NULL DEFAULT 'strict_pre_cutoff',
    "Sensitivity"   VARCHAR NOT NULL DEFAULT 'normal',    -- normal|restricted|protected
    "AllowedTasks"  TEXT[] NOT NULL DEFAULT '{}',
    "MissingPolicy" VARCHAR NOT NULL DEFAULT 'null_ok',
    "StalePolicy"   VARCHAR NOT NULL DEFAULT 'invalidate_on_source_change',
    "Owner"         VARCHAR,
    "ApprovalStatus" VARCHAR NOT NULL DEFAULT 'draft',    -- draft|approved|retired
    "CreatedAt"     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT "chk_featuredef_sensitivity" CHECK ("Sensitivity" IN ('normal','restricted','protected')),
    CONSTRAINT "chk_featuredef_approval"   CHECK ("ApprovalStatus" IN ('draft','approved','retired'))
);
COMMENT ON TABLE "FeatureDefinition" IS 'Governed feature catalogue. Protected/restricted features are excluded from prediction schemas unless a reviewed aggregate task permits them.';

CREATE TABLE IF NOT EXISTS "FeatureSchemaVersion" (
    "FeatureSchemaVersionID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "SchemaName"    VARCHAR NOT NULL,
    "Version"       VARCHAR NOT NULL,
    "FeatureDefinitionIDs" JSONB NOT NULL DEFAULT '[]'::jsonb,   -- ordered list of FeatureDefinitionID
    "Task"          VARCHAR,                                       -- approved task this schema serves
    "Status"        VARCHAR NOT NULL DEFAULT 'draft',              -- draft|approved|retired
    "ApprovedByActor" VARCHAR,
    "ApprovedAt"    TIMESTAMPTZ,
    "CreatedAt"     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT "uq_featureschemaversion" UNIQUE ("SchemaName", "Version"),
    CONSTRAINT "chk_featureschema_status" CHECK ("Status" IN ('draft','approved','retired'))
);
COMMENT ON TABLE "FeatureSchemaVersion" IS 'A versioned, approvable set of feature definitions. Models bind to an exact schema version (strict contract).';

CREATE TABLE IF NOT EXISTS "TrainingDatasetSnapshot" (
    "TrainingDatasetSnapshotID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Name"          VARCHAR NOT NULL,
    "FeatureSchemaVersionID" BIGINT REFERENCES "FeatureSchemaVersion" ("FeatureSchemaVersionID"),
    "TimeSplit"     JSONB NOT NULL DEFAULT '{}'::jsonb,   -- {train:[..],val:[..],test:[..]}
    "GeoSplit"      JSONB NOT NULL DEFAULT '{}'::jsonb,
    "RowCount"      BIGINT,
    "ObservationCutoff" TIMESTAMPTZ,
    "LabelWindowStart"  TIMESTAMPTZ,
    "LabelWindowEnd"    TIMESTAMPTZ,
    "Exclusions"    JSONB NOT NULL DEFAULT '{}'::jsonb,
    "ApprovalStatus" VARCHAR NOT NULL DEFAULT 'draft',
    "ContentHash"   VARCHAR,
    "CreatedAt"     TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE "TrainingDatasetSnapshot" IS 'A reproducible training dataset with explicit time/geographic splits and label windows.';

CREATE TABLE IF NOT EXISTS "FeatureSnapshot" (
    "FeatureSnapshotID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "FeatureSchemaVersionID" BIGINT REFERENCES "FeatureSchemaVersion" ("FeatureSchemaVersionID"),
    "SubjectKind"   VARCHAR NOT NULL,          -- area_unit|area_district|beat_window|case|aggregate
    "SubjectRefID"  VARCHAR NOT NULL,          -- e.g. UnitID/DistrictID/CaseMasterID as text
    "ObservationCutoff" TIMESTAMPTZ NOT NULL,
    "Values"        JSONB NOT NULL DEFAULT '{}'::jsonb,
    "SourceVersions" JSONB NOT NULL DEFAULT '{}'::jsonb,  -- source_record/version ids used
    "QualityStatus" VARCHAR NOT NULL DEFAULT 'ok',        -- ok|partial|stale
    "ContentHash"   VARCHAR NOT NULL,
    "IsImmutable"   BOOLEAN NOT NULL DEFAULT TRUE,
    "SupersededByFeatureSnapshotID" BIGINT REFERENCES "FeatureSnapshot" ("FeatureSnapshotID"),
    "CreatedAt"     TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE "FeatureSnapshot" IS 'Immutable feature vector with source versions, observation cutoff, quality status and hash. Every prediction ties to one.';

-- =============================================================================
-- 2. LABELS (Group 11) — from verified outcomes only, leakage-safe
-- =============================================================================
CREATE TABLE IF NOT EXISTS "OutcomeLabel" (
    "OutcomeLabelID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CaseMasterID"  INTEGER REFERENCES "CaseMaster" ("CaseMasterID"),
    "SubjectKind"   VARCHAR NOT NULL DEFAULT 'case',
    "SubjectRefID"  VARCHAR,
    "LabelName"     VARCHAR NOT NULL,
    "LabelValue"    VARCHAR,
    "OutcomeObservationID" BIGINT REFERENCES "OutcomeObservation" ("OutcomeObservationID"),
    "ObservationCutoff" TIMESTAMPTZ NOT NULL,
    "LabelWindowStart"  TIMESTAMPTZ NOT NULL,
    "LabelWindowEnd"    TIMESTAMPTZ NOT NULL,
    "SplitTag"      VARCHAR,                       -- train|val|test|geo_holdout
    "IsSynthetic"   BOOLEAN NOT NULL DEFAULT TRUE,
    "CreatedAt"     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT "chk_outcomelabel_window" CHECK ("LabelWindowEnd" >= "LabelWindowStart"),
    -- Leakage guard: the label window must start no earlier than the cutoff.
    CONSTRAINT "chk_outcomelabel_cutoff" CHECK ("LabelWindowStart" >= "ObservationCutoff")
);
COMMENT ON TABLE "OutcomeLabel" IS 'Training labels derived ONLY from verified OutcomeObservations after the observation cutoff. Never from the input feature formula.';

-- =============================================================================
-- 3. PREDICTION REQUEST / RESULT / REVIEW (Group 11)
-- =============================================================================
CREATE TABLE IF NOT EXISTS "PredictionRequest" (
    "PredictionRequestID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "ModelVersionID"   INTEGER REFERENCES "ModelVersion" ("ModelVersionID"),
    "FeatureSnapshotID" BIGINT REFERENCES "FeatureSnapshot" ("FeatureSnapshotID"),
    "RequestKind"      VARCHAR NOT NULL DEFAULT 'batch',
    "IdempotencyKey"   VARCHAR UNIQUE,
    "Status"           VARCHAR NOT NULL DEFAULT 'queued',
    "RequestedByActor" VARCHAR,
    "CreatedAt"        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT "chk_predreq_status" CHECK ("Status" IN
        ('queued','running','completed','failed','stale','superseded','reviewed','rejected'))
);
COMMENT ON TABLE "PredictionRequest" IS 'A governed prediction request bound to an exact model + immutable feature snapshot. Idempotent.';

CREATE TABLE IF NOT EXISTS "PredictionResult" (
    "PredictionResultID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PredictionRequestID" BIGINT REFERENCES "PredictionRequest" ("PredictionRequestID"),
    "ModelVersionID"   INTEGER REFERENCES "ModelVersion" ("ModelVersionID"),
    "FeatureSnapshotID" BIGINT REFERENCES "FeatureSnapshot" ("FeatureSnapshotID"),
    "OutputJSON"       JSONB NOT NULL DEFAULT '{}'::jsonb,
    "Explanation"      JSONB NOT NULL DEFAULT '{}'::jsonb,
    "Limitations"      TEXT,
    "Confidence"       NUMERIC(6,5) CHECK ("Confidence" IS NULL OR "Confidence" BETWEEN 0 AND 1),
    "LowerInterval"    NUMERIC,
    "UpperInterval"    NUMERIC,
    "ExpiresAt"        TIMESTAMPTZ,
    "IsStale"          BOOLEAN NOT NULL DEFAULT FALSE,
    "SupersededByResultID" BIGINT REFERENCES "PredictionResult" ("PredictionResultID"),
    "CreatedAt"        TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE "PredictionResult" IS 'Reviewable prediction output with explanation, limitations, interval, expiry and supersession (history preserved).';

CREATE TABLE IF NOT EXISTS "PredictionReview" (
    "PredictionReviewID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PredictionResultID" BIGINT NOT NULL REFERENCES "PredictionResult" ("PredictionResultID") ON DELETE CASCADE,
    "ReviewerActor"    VARCHAR,
    "Decision"         VARCHAR NOT NULL DEFAULT 'accept',   -- accept|override|reject
    "OverrideReason"   TEXT,
    "ReviewedAt"       TIMESTAMPTZ NOT NULL DEFAULT now(),
    "CreatedAt"        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT "chk_predreview_decision" CHECK ("Decision" IN ('accept','override','reject'))
);
COMMENT ON TABLE "PredictionReview" IS 'Mandatory human review/override for a prediction result. Predictions are decision-support only.';

-- =============================================================================
-- 4. MODELVERSION GOVERNANCE EXTENSIONS (Group 12) — additive columns
-- =============================================================================
ALTER TABLE "ModelVersion" ADD COLUMN IF NOT EXISTS "ArtifactDigest"  VARCHAR;
ALTER TABLE "ModelVersion" ADD COLUMN IF NOT EXISTS "ImageDigest"     VARCHAR;
ALTER TABLE "ModelVersion" ADD COLUMN IF NOT EXISTS "TrainingDatasetSnapshotID" BIGINT REFERENCES "TrainingDatasetSnapshot" ("TrainingDatasetSnapshotID");
ALTER TABLE "ModelVersion" ADD COLUMN IF NOT EXISTS "FeatureSchemaVersionID"    BIGINT REFERENCES "FeatureSchemaVersion" ("FeatureSchemaVersionID");
ALTER TABLE "ModelVersion" ADD COLUMN IF NOT EXISTS "ApprovalStatus"  VARCHAR;   -- draft|approved|shadow|retired|rolled_back
ALTER TABLE "ModelVersion" ADD COLUMN IF NOT EXISTS "ApprovedBy"      VARCHAR;
ALTER TABLE "ModelVersion" ADD COLUMN IF NOT EXISTS "ApprovedAt"      TIMESTAMPTZ;
ALTER TABLE "ModelVersion" ADD COLUMN IF NOT EXISTS "EvaluationReport" JSONB;
ALTER TABLE "ModelVersion" ADD COLUMN IF NOT EXISTS "Environment"     VARCHAR;   -- local|disposable_test|hackathon_demo
ALTER TABLE "ModelVersion" ADD COLUMN IF NOT EXISTS "RollbackToModelVersionID" INTEGER REFERENCES "ModelVersion" ("ModelVersionID");
ALTER TABLE "ModelVersion" ADD COLUMN IF NOT EXISTS "IsRollbackTarget" BOOLEAN NOT NULL DEFAULT FALSE;

-- =============================================================================
-- 5. INDEXES
-- =============================================================================
CREATE INDEX IF NOT EXISTS "idx_featuresnapshot_schema"  ON "FeatureSnapshot" ("FeatureSchemaVersionID");
CREATE INDEX IF NOT EXISTS "idx_featuresnapshot_subject" ON "FeatureSnapshot" ("SubjectKind", "SubjectRefID");
CREATE INDEX IF NOT EXISTS "idx_featuresnapshot_super"   ON "FeatureSnapshot" ("SupersededByFeatureSnapshotID");
CREATE INDEX IF NOT EXISTS "idx_outcomelabel_case"       ON "OutcomeLabel" ("CaseMasterID");
CREATE INDEX IF NOT EXISTS "idx_outcomelabel_split"      ON "OutcomeLabel" ("SplitTag");
CREATE INDEX IF NOT EXISTS "idx_predrequest_model"       ON "PredictionRequest" ("ModelVersionID");
CREATE INDEX IF NOT EXISTS "idx_predrequest_snapshot"    ON "PredictionRequest" ("FeatureSnapshotID");
CREATE INDEX IF NOT EXISTS "idx_predrequest_status"      ON "PredictionRequest" ("Status");
CREATE INDEX IF NOT EXISTS "idx_predresult_request"      ON "PredictionResult" ("PredictionRequestID");
CREATE INDEX IF NOT EXISTS "idx_predresult_model"        ON "PredictionResult" ("ModelVersionID");
CREATE INDEX IF NOT EXISTS "idx_predreview_result"       ON "PredictionReview" ("PredictionResultID");
CREATE INDEX IF NOT EXISTS "gin_featuredef_tasks"        ON "FeatureDefinition" USING GIN ("AllowedTasks");
CREATE INDEX IF NOT EXISTS "gin_featuresnapshot_values"  ON "FeatureSnapshot" USING GIN ("Values");

-- =============================================================================
-- 6. Grants + RLS disabled/NO FORCE + global verification (hackathon).
-- =============================================================================
DO $$
DECLARE t TEXT;
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'drishti_readonly') THEN
        FOREACH t IN ARRAY ARRAY[
            'FeatureDefinition','FeatureSchemaVersion','TrainingDatasetSnapshot',
            'FeatureSnapshot','OutcomeLabel','PredictionRequest','PredictionResult',
            'PredictionReview'
        ] LOOP
            EXECUTE format('GRANT SELECT ON %I TO drishti_readonly', t);
        END LOOP;
    END IF;
END$$;

SELECT fn_disable_rls_all_app();
SELECT fn_assert_rls_disabled();

COMMIT;

