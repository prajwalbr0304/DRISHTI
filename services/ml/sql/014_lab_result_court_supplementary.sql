-- =============================================================================
-- DRISHTI migration 014 — optional manual lab-result metadata + supplementary
--                          chargesheet court-event type (Phase 7)
-- Target: PostgreSQL 15+ / AWS RDS (live PG 17.x)
-- Depends on: 006_ingestion_evidence.sql, 007_identity_case_workflow.sql,
--             005_security_rls_audit.sql
-- =============================================================================
--
-- Phase 7 adds contextual forms for statements, property/seizure, court events,
-- bail, disposition and outcomes — all of which already have tables (migration
-- 007). Two small additive gaps remain:
--
--   1. LabResult — a MINIMAL, manually entered forensic/lab metadata record
--      (NOT a full lab workflow). All fields are manual and clearly synthetic;
--      a digital report may be LINKED (EvidenceItem) but its content is never
--      auto-parsed (no OCR/extraction).
--   2. CourtEvent gains a 'supplementary_chargesheet' event type so a
--      supplementary/final report can be logged as a court document.
--
-- RLS stays DISABLED + NO FORCE (hackathon). No RLS policies. Additive +
-- idempotent: safe to run repeatedly.
-- =============================================================================

BEGIN;

-- ---------------------------------------------------------------------------
-- 1. LabResult (optional manual metadata)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS "LabResult" (
    "LabResultID"    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CaseMasterID"   INTEGER NOT NULL REFERENCES "CaseMaster" ("CaseMasterID"),
    "PropertyItemID" BIGINT REFERENCES "PropertyItem" ("PropertyItemID"),
    "SeizureID"      BIGINT REFERENCES "Seizure" ("SeizureID"),
    "TestType"       VARCHAR NOT NULL,               -- e.g. chemical | dna | ballistic | fingerprint | toxicology | other
    "LabName"        VARCHAR,                          -- synthetic lab name
    "SyntheticReference" VARCHAR,                     -- unmistakably synthetic ref
    "RequestedAt"    TIMESTAMPTZ,
    "ResultAt"       TIMESTAMPTZ,
    "ResultSummary"  TEXT,                             -- manual summary (no auto-extraction)
    "Status"         VARCHAR NOT NULL DEFAULT 'requested',  -- requested|in_progress|completed|inconclusive|cancelled
    "ReportEvidenceItemID" BIGINT REFERENCES "EvidenceItem" ("EvidenceItemID"),  -- linked digital report
    "AccessClassification" VARCHAR NOT NULL DEFAULT 'demo_normal',
    "IsSynthetic"    BOOLEAN NOT NULL DEFAULT TRUE,
    "CreatedByActor" VARCHAR,
    "CreatedAt"      TIMESTAMPTZ NOT NULL DEFAULT now(),
    "UpdatedAt"      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT "chk_labresult_status" CHECK ("Status" IN
        ('requested','in_progress','completed','inconclusive','cancelled'))
);
COMMENT ON TABLE "LabResult" IS
    'Minimal, MANUALLY entered lab/forensic result metadata (Phase 7). Not a full lab workflow. A digital report may be linked (EvidenceItem) but never auto-parsed.';

CREATE INDEX IF NOT EXISTS "idx_labresult_case"     ON "LabResult" ("CaseMasterID");
CREATE INDEX IF NOT EXISTS "idx_labresult_property" ON "LabResult" ("PropertyItemID");
CREATE INDEX IF NOT EXISTS "idx_labresult_status"   ON "LabResult" ("Status");

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'trg_labresult_updated') THEN
        CREATE TRIGGER "trg_labresult_updated" BEFORE UPDATE ON "LabResult"
            FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();
    END IF;
END$$;

-- ---------------------------------------------------------------------------
-- 2. CourtEvent: documented EventType allow-list incl. 'supplementary_chargesheet'.
--    Phase-1 CourtEvent had EventType as a free varchar (no CHECK). All existing
--    values (chargesheet_filed/hearing/judgment) are in the new set. Idempotent:
--    drop-if-exists then add.
-- ---------------------------------------------------------------------------
ALTER TABLE "CourtEvent" DROP CONSTRAINT IF EXISTS "chk_courtevent_type";
ALTER TABLE "CourtEvent" ADD CONSTRAINT "chk_courtevent_type" CHECK ("EventType" IN
    ('chargesheet_filed','supplementary_chargesheet','hearing','remand',
     'framing_of_charges','judgment','adjournment','bail_hearing','transfer'));

-- ---------------------------------------------------------------------------
-- 3. Grants + RLS disabled/NO FORCE + verification.
-- ---------------------------------------------------------------------------
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'drishti_readonly') THEN
        GRANT SELECT ON "LabResult" TO drishti_readonly;
    END IF;
END$$;

SELECT fn_disable_rls_all_app();
SELECT fn_assert_rls_disabled();

COMMIT;

