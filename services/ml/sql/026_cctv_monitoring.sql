-- =============================================================================
-- DRISHTI migration 026 — CCTV monitoring (video-analytics review + dispatch)
-- Target: PostgreSQL 15+ / AWS RDS PostgreSQL (ap-south-1)
-- Depends on: police_fir_schema.sql (State, District, Unit),
--             009_jurisdiction_external_events.sql (UnitLocation + GIST index,
--                 fn_point_in_district), 005_security_rls_audit.sql
--                 (fn_disable_rls_all_app / fn_assert_rls_disabled)
-- =============================================================================
--
-- This is the ANALYTICS MIRROR of the Data Store-native CCTV tables defined in
-- app/datastore/cctv_schema.py. Catalyst Data Store is authoritative for the
-- operational surface; this mirror is reconstructable, keyed by the same
-- ExternalIDs, and exists so the estate can be analysed with PostGIS (camera
-- coverage vs hotspots, response-distance distributions, false-positive rates by
-- class and camera). It is never the browser CRUD path.
--
-- The pipeline these tables record:
--
--   1. "Camera" — the monitored estate. A real point geometry so coverage can be
--      compared against incident hotspots, plus a per-camera analytics switch and
--      an optional detector profile (which incident classes this camera is
--      watched for).
--   2. "PatrolUnit" — dispatchable responders (station desks, Hoysala patrol
--      cars, Cheetah traffic bikes, control rooms) with a point geometry, so
--      "nearest responder" is a real KNN query rather than a guess.
--   3. "CctvDetection" — APPEND-ONLY detector output. Carries "DetectorKind"
--      ('synthetic_replay' | 'external_analytics') and "DetectorLabel" so the
--      provenance of every claim is recorded, plus "Confidence" and
--      "QualityFlag" so a weak detection can never read as a certainty. Unique
--      on "SourceRecordID", which is what makes ingestion idempotent.
--   4. "CctvAlert" — the REVIEWABLE alert. Starts at 'proposed'. A recorded human
--      actor moves it to 'confirmed' or 'dismissed'; a dismissal keeps its
--      reason, which is the only honest measure of detector precision.
--   5. "CctvDispatch" — the nearest-responder assignment, with the ranking inputs
--      kept in "Reason" (distance, geometry source, ETA assumption, rule) so the
--      choice is explainable after the fact.
--   6. "CctvActivity" — APPEND-ONLY audit of every camera/alert/dispatch action.
--
-- GOVERNANCE — the important part:
--   * NOTHING AUTO-DISPATCHES. A detection can only propose an alert; a human
--     confirms the alert; a human separately confirms the dispatch. The
--     CHECK constraints below encode that a confirmed/dismissed alert must carry
--     a reviewer, and that a dismissal must carry a reason.
--   * This schema stores NO frame or clip BYTES and no biometric descriptor. A
--     detection points at an object key in the evidence bucket; bounding boxes
--     are normalised geometry with a class label ('person', 'vehicle'), never an
--     identity. Face recognition is a separate, separately-gated capability
--     (025) and is deliberately not joined to this table.
--   * Detection and activity tables are append-only by trigger, so a detection
--     can never be rewritten after review to agree with the decision made.
--
-- HACKATHON SCOPE: synthetic data only. RLS stays DISABLED (no policies).
-- Additive + idempotent: safe to re-run.
-- =============================================================================

BEGIN;

