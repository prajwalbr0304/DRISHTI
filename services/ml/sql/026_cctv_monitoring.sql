DECLARE
    t TEXT;
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname='drishti_readonly') THEN
        FOREACH t IN ARRAY ARRAY[
            'Camera','PatrolUnit','CctvDetection','CctvAlert','CctvDispatch',
            'CctvActivity'
        ] LOOP
            EXECUTE format('GRANT SELECT ON %I TO drishti_readonly;', t);
        END LOOP;
        FOREACH t IN ARRAY ARRAY[
            'vw_cctv_detector_precision','vw_cctv_response_performance',
            'vw_cctv_camera_geo_mismatch'
        ] LOOP
            EXECUTE format('GRANT SELECT ON %I TO drishti_readonly;', t);
        END LOOP;
    END IF;
END$$;

-- RLS + FORCE RLS stay DISABLED across every application table (hackathon).
-- No RLS policy is created for the mirror. The access boundary is the
-- Catalyst-authenticated API + the server-side CCTV role middleware.
SELECT fn_disable_rls_all_app();
SELECT fn_assert_rls_disabled();

COMMIT;
