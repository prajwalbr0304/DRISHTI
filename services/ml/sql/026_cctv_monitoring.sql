-- 9. Analysis helpers
-- =============================================================================
-- Nearest dispatchable responders to a point, using the GIST KNN operator.
-- This is the SQL form of app/cctv/dispatch.py::rank_responders, kept here so the
-- same ranking can be reproduced in analysis without going through the API.
CREATE OR REPLACE FUNCTION fn_cctv_nearest_responders(
    p_lon        DOUBLE PRECISION,
    p_lat        DOUBLE PRECISION,
    p_max_km     DOUBLE PRECISION DEFAULT 25.0,
    p_limit      INTEGER DEFAULT 5
)
RETURNS TABLE (
    patrol_unit_id BIGINT,
    code           VARCHAR,
    name           VARCHAR,
    kind           VARCHAR,
    status         VARCHAR,
    district_id    INTEGER,
    distance_km    DOUBLE PRECISION
)
LANGUAGE sql
STABLE
AS $$
    SELECT p."PatrolUnitID", p."Code", p."Name", p."Kind", p."Status", p."DistrictID",
           ST_Distance(p."geom"::geography,
                       ST_SetSRID(ST_MakePoint(p_lon, p_lat), 4326)::geography) / 1000.0
    FROM "PatrolUnit" p
    WHERE p."DeletedAt" IS NULL
      AND p."Status" <> 'offline'
      AND ST_DWithin(p."geom"::geography,
                     ST_SetSRID(ST_MakePoint(p_lon, p_lat), 4326)::geography,
                     p_max_km * 1000.0)
    ORDER BY p."geom" <-> ST_SetSRID(ST_MakePoint(p_lon, p_lat), 4326)
    LIMIT GREATEST(1, p_limit);
$$;
COMMENT ON FUNCTION fn_cctv_nearest_responders(DOUBLE PRECISION, DOUBLE PRECISION, DOUBLE PRECISION, INTEGER) IS
    'KNN nearest available responders to a point, within a radius. SQL mirror of the API ranking.';

-- Per-class / per-camera review outcomes: the honest precision read-out. A demo
-- that shows detections without showing how many were dismissed is marketing.
CREATE OR REPLACE VIEW "vw_cctv_detector_precision" AS
SELECT
    a."AlertType"                                        AS "AlertType",
    c."Code"                                             AS "CameraCode",
    c."Name"                                             AS "CameraName",
    a."DistrictID"                                       AS "DistrictID",
    COUNT(*)                                             AS "TotalAlerts",
    COUNT(*) FILTER (WHERE a."Status" = 'proposed')       AS "AwaitingReview",
    COUNT(*) FILTER (WHERE a."Status" IN ('confirmed','dispatched','resolved'))
                                                         AS "Confirmed",
    COUNT(*) FILTER (WHERE a."Status" = 'dismissed')      AS "Dismissed",
    COUNT(*) FILTER (WHERE a."DismissReason" = 'false_positive')
                                                         AS "FalsePositives",
    ROUND(AVG(a."Confidence")::numeric, 4)               AS "MeanConfidence",
    -- Precision is only defined over REVIEWED alerts; NULL while nothing has been
    -- reviewed, rather than a misleading 0 or 1.
    CASE WHEN COUNT(*) FILTER (WHERE a."Status" <> 'proposed') > 0
         THEN ROUND(
              (COUNT(*) FILTER (WHERE a."Status" IN ('confirmed','dispatched','resolved'))::numeric
               / COUNT(*) FILTER (WHERE a."Status" <> 'proposed')), 4)
         ELSE NULL
    END                                                  AS "ReviewedPrecision"
FROM "CctvAlert" a
JOIN "Camera" c ON c."CameraID" = a."CameraID"
WHERE a."DeletedAt" IS NULL
GROUP BY a."AlertType", c."Code", c."Name", a."DistrictID";
COMMENT ON VIEW "vw_cctv_detector_precision" IS
    'Review outcomes per class and camera. ReviewedPrecision is NULL until alerts have actually been reviewed.';

-- Response-time distribution for dispatches that were actually sent.
CREATE OR REPLACE VIEW "vw_cctv_response_performance" AS
SELECT
    d."CctvDispatchID"                                   AS "CctvDispatchID",
    d."CctvAlertID"                                      AS "CctvAlertID",
    a."AlertType"                                        AS "AlertType",
    a."Severity"                                         AS "Severity",
    d."UnitName"                                         AS "UnitName",
    d."DistanceKm"                                       AS "DistanceKm",
    d."EtaMinutes"                                       AS "EtaMinutes",
    d."Reason" ->> 'geometry_source'                     AS "GeometrySource",
    EXTRACT(EPOCH FROM (d."DispatchedAt" - a."CreatedAt")) / 60.0
                                                         AS "DetectionToDispatchMinutes",
    EXTRACT(EPOCH FROM (a."ReviewedAt" - a."CreatedAt")) / 60.0
                                                         AS "DetectionToReviewMinutes",
    EXTRACT(EPOCH FROM (d."OnsiteAt" - d."DispatchedAt")) / 60.0
                                                         AS "DispatchToOnsiteMinutes",
    d."Status"                                           AS "Status"
FROM "CctvDispatch" d
JOIN "CctvAlert" a ON a."CctvAlertID" = d."CctvAlertID"
WHERE d."DeletedAt" IS NULL
  AND d."DispatchedAt" IS NOT NULL;
COMMENT ON VIEW "vw_cctv_response_performance" IS
    'Detection -> review -> dispatch -> onsite timings, with the actual vs estimated travel comparison. Only rows that were really dispatched.';

-- Camera coverage sanity: which cameras sit outside their claimed district.
-- A camera whose point falls outside the district it is filed under is a data
-- error that would silently corrupt every district-scoped query above it.
CREATE OR REPLACE VIEW "vw_cctv_camera_geo_mismatch" AS
SELECT c."CameraID", c."Code", c."Name", c."DistrictID",
       ST_X(c."geom") AS "Lon", ST_Y(c."geom") AS "Lat"
FROM "Camera" c
WHERE c."DeletedAt" IS NULL
  AND c."DistrictID" IS NOT NULL
  AND NOT fn_point_in_district(c."DistrictID", ST_X(c."geom"), ST_Y(c."geom"));
COMMENT ON VIEW "vw_cctv_camera_geo_mismatch" IS
    'Cameras whose point geometry falls outside the district they are filed under (degrades safely to empty when no boundary is loaded).';

-- =============================================================================
-- 10. Read-only grants (retained analytics reader) + RLS-disabled verification
