-- =============================================================================
-- 8. Append-only enforcement (detections + activity)
-- =============================================================================
-- A detection that could be edited after review is worthless as evidence of what
-- the detector actually claimed, so the database refuses the write outright
-- rather than trusting every future code path to remember.
CREATE OR REPLACE FUNCTION fn_cctv_forbid_mutation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION
        '%.% is append-only: % is forbidden',
        TG_TABLE_SCHEMA, TG_TABLE_NAME, TG_OP
        USING HINT = 'Insert a new row (e.g. a superseding detection) instead.';
END$$;
COMMENT ON FUNCTION fn_cctv_forbid_mutation() IS
    'Raises on UPDATE/DELETE for the append-only CCTV tables.';

DROP TRIGGER IF EXISTS "trg_cctvdetection_append_only" ON "CctvDetection";
CREATE TRIGGER "trg_cctvdetection_append_only"
    BEFORE UPDATE OR DELETE ON "CctvDetection"
    FOR EACH ROW EXECUTE FUNCTION fn_cctv_forbid_mutation();

DROP TRIGGER IF EXISTS "trg_cctvactivity_append_only" ON "CctvActivity";
CREATE TRIGGER "trg_cctvactivity_append_only"
    BEFORE UPDATE OR DELETE ON "CctvActivity"
    FOR EACH ROW EXECUTE FUNCTION fn_cctv_forbid_mutation();

