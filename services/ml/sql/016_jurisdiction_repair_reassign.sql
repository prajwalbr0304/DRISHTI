--
-- Phase 9 completes the jurisdiction data path. Migration 009 already persisted
-- versioned state/district/unit(SHO) boundaries + UnitLocation and the
-- state/district containment functions + vw_caseversion_containment. This
-- migration adds:
--   1. fn_point_in_unit — unit/SHO-level containment (the missing helper).
--   2. vw_location_observation_containment — spatial check for imported GPS.
--   3. JurisdictionReassignment — an append-only audit of REVIEWED jurisdiction
--      reassignments / overrides / quarantines (no row is ever silently moved).
--   4. SpatialRepairRun — before/after metadata for a containment scan/repair.
--   5. widens the boundary Level allow-list to include 'taluk' so administrative
--      taluk boundaries can also be persisted (loaded by the boundary loader).
