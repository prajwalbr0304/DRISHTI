        GRANT SELECT ON "SpatialRepairRun" TO drishti_readonly;
        GRANT SELECT ON "vw_location_observation_containment" TO drishti_readonly;
    END IF;
END$$;

SELECT fn_disable_rls_all_app();
SELECT fn_assert_rls_disabled();

COMMIT;

