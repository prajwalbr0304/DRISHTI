BEGIN;

-- =============================================================================
-- 1. Widen the boundary Level allow-list to persist administrative taluks.
-- =============================================================================
ALTER TABLE "JurisdictionBoundary" DROP CONSTRAINT IF EXISTS "chk_jurisdiction_level";
ALTER TABLE "JurisdictionBoundary" ADD CONSTRAINT "chk_jurisdiction_level"
    CHECK ("Level" IN ('state','district','taluk','unit','beat','sho'));

-- =============================================================================
-- 2. Unit/SHO-level containment helper (state + district already exist).
-- =============================================================================
CREATE OR REPLACE FUNCTION fn_point_in_unit(p_unit_id INTEGER,
                                            p_lon DOUBLE PRECISION,
                                            p_lat DOUBLE PRECISION)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
AS $$
    SELECT COALESCE(bool_or(ST_Contains(b."geom",
              ST_SetSRID(ST_MakePoint(p_lon, p_lat), 4326))), FALSE)
    FROM "JurisdictionBoundary" b
    WHERE b."Level" IN ('unit', 'sho') AND b."IsCurrent"
      AND b."UnitID" = p_unit_id;
$$;
COMMENT ON FUNCTION fn_point_in_unit(INTEGER, DOUBLE PRECISION, DOUBLE PRECISION) IS
    'TRUE if the point lies inside the given unit/SHO jurisdiction (current version).';

-- =============================================================================
-- 3. LocationObservation containment view (imported GPS, Phase 8).
-- =============================================================================
CREATE OR REPLACE VIEW "vw_location_observation_containment" AS
SELECT
    lo."LocationObservationID",
    lo."CaseMasterID",
    lo."DistrictID",
    ST_X(lo."geom") AS "Longitude",
    ST_Y(lo."geom") AS "Latitude",
    fn_point_in_state(ST_X(lo."geom")::double precision,
                      ST_Y(lo."geom")::double precision) AS "InState",
    CASE WHEN lo."DistrictID" IS NULL THEN NULL
         ELSE fn_point_in_district(lo."DistrictID",
                                   ST_X(lo."geom")::double precision,
                                   ST_Y(lo."geom")::double precision) END AS "InDistrict"
FROM "LocationObservation" lo
WHERE lo."geom" IS NOT NULL;
COMMENT ON VIEW "vw_location_observation_containment" IS
    'Per-LocationObservation spatial containment against state + its (optional) district.';

-- =============================================================================
-- 4. Reviewed jurisdiction reassignment / override audit (no silent moves).
-- =============================================================================
CREATE TABLE IF NOT EXISTS "JurisdictionReassignment" (
    "JurisdictionReassignmentID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CaseMasterID"    INTEGER NOT NULL REFERENCES "CaseMaster" ("CaseMasterID"),
    "FromCaseVersionID" BIGINT REFERENCES "CaseVersion" ("CaseVersionID"),
    "ToCaseVersionID"   BIGINT REFERENCES "CaseVersion" ("CaseVersionID"),
    "Action"          VARCHAR NOT NULL DEFAULT 'reassign',  -- reassign|override|quarantine|regenerate
    "FromDistrictID"  INTEGER REFERENCES "District" ("DistrictID"),
    "ToDistrictID"    INTEGER REFERENCES "District" ("DistrictID"),
    "FromUnitID"      INTEGER REFERENCES "Unit" ("UnitID"),
    "ToUnitID"        INTEGER REFERENCES "Unit" ("UnitID"),
    "Reason"          TEXT,
    "ReviewerActor"   VARCHAR,
    "SourceRecordID"  BIGINT REFERENCES "SourceRecord" ("SourceRecordID"),
    "DataQualityIssueID" BIGINT REFERENCES "DataQualityIssue" ("DataQualityIssueID"),
    "BeforeState"     JSONB NOT NULL DEFAULT '{}'::jsonb,
    "AfterState"      JSONB NOT NULL DEFAULT '{}'::jsonb,
    "CreatedAt"       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT "chk_jurisreassign_action" CHECK ("Action" IN
        ('reassign','override','quarantine','regenerate'))
);
COMMENT ON TABLE "JurisdictionReassignment" IS 'Append-only audit of REVIEWED jurisdiction reassignments/overrides/quarantines. A mismatched case is never silently moved.';

-- =============================================================================
-- 5. Spatial repair/scan run metadata (before/after containment counts).
-- =============================================================================
CREATE TABLE IF NOT EXISTS "SpatialRepairRun" (
    "SpatialRepairRunID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "RunKey"          VARCHAR,
    "Scope"           VARCHAR NOT NULL DEFAULT 'all',   -- caseversion|location_observation|all
    "CheckedCount"    INTEGER,
    "OutOfStateCount" INTEGER,
    "OutOfDistrictCount" INTEGER,
    "IssuesRaised"    INTEGER,
    "Totals"          JSONB NOT NULL DEFAULT '{}'::jsonb,
    "Actor"           VARCHAR,
    "CreatedAt"       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT "chk_spatialrepair_scope" CHECK ("Scope" IN
        ('caseversion','location_observation','all'))
);
COMMENT ON TABLE "SpatialRepairRun" IS 'One containment scan/repair run: before/after out-of-state/out-of-district counts + issues raised.';

-- =============================================================================
-- 6. INDEXES
-- =============================================================================
CREATE INDEX IF NOT EXISTS "idx_jurisreassign_case"   ON "JurisdictionReassignment" ("CaseMasterID");
CREATE INDEX IF NOT EXISTS "idx_jurisreassign_action" ON "JurisdictionReassignment" ("Action");
CREATE INDEX IF NOT EXISTS "idx_jurisreassign_dq"     ON "JurisdictionReassignment" ("DataQualityIssueID");
CREATE INDEX IF NOT EXISTS "idx_spatialrepair_created" ON "SpatialRepairRun" ("CreatedAt");

-- =============================================================================
-- 7. Grants + RLS disabled/NO FORCE + global verification (hackathon).
