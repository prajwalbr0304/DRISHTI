-- Validates the 18-digit CrimeNo format and auto-derives CaseNo as the last 9
-- digits of CrimeNo when CaseNo is not supplied (per the diagram description).
CREATE OR REPLACE FUNCTION fn_casemaster_biu()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW."CrimeNo" IS NOT NULL AND NEW."CrimeNo" !~ '^[0-9]{18}$' THEN
        RAISE EXCEPTION 'CrimeNo must be exactly 18 digits (got: %)', NEW."CrimeNo";
    END IF;

    IF NEW."CaseNo" IS NULL AND NEW."CrimeNo" IS NOT NULL THEN
        NEW."CaseNo" := RIGHT(NEW."CrimeNo", 9);
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER "trg_casemaster_biu"
    BEFORE INSERT OR UPDATE ON "CaseMaster"
    FOR EACH ROW
    EXECUTE FUNCTION fn_casemaster_biu();

