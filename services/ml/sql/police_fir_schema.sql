-- Fully resolved FIR listing with human-readable lookup values.
CREATE OR REPLACE VIEW "vw_fir_full" AS
SELECT
    cm."CaseMasterID",
    cm."CrimeNo",
    cm."CaseNo",
    cm."CrimeRegisteredDate",
    cat."LookupValue"        AS "CaseCategory",
    grv."LookupValue"        AS "GravityOffence",
    ch."CrimeGroupName"      AS "CrimeMajorHead",
    csh."CrimeHeadName"      AS "CrimeMinorHead",
    st."CaseStatusName"      AS "CaseStatus",
    ct."CourtName"           AS "Court",
    u."UnitName"             AS "PoliceStation",
    d."DistrictName"         AS "District",
    s."StateName"            AS "State",
    (e."FirstName")          AS "RegisteredByOfficer",
    cm."IncidentFromDate",
    cm."IncidentToDate",
    cm."InfoReceivedPSDate",
    cm."latitude",
    cm."longitude",
    cm."geom",
    cm."BriefFacts"
FROM "CaseMaster" cm
LEFT JOIN "CaseCategory"     cat ON cat."CaseCategoryID"   = cm."CaseCategoryID"
LEFT JOIN "GravityOffence"   grv ON grv."GravityOffenceID" = cm."GravityOffenceID"
LEFT JOIN "CrimeHead"        ch  ON ch."CrimeHeadID"       = cm."CrimeMajorHeadID"
LEFT JOIN "CrimeSubHead"     csh ON csh."CrimeSubHeadID"   = cm."CrimeMinorHeadID"
LEFT JOIN "CaseStatusMaster" st  ON st."CaseStatusID"      = cm."CaseStatusID"
LEFT JOIN "Court"            ct  ON ct."CourtID"           = cm."CourtID"
LEFT JOIN "Unit"             u   ON u."UnitID"             = cm."PoliceStationID"
LEFT JOIN "District"         d   ON d."DistrictID"         = u."DistrictID"
LEFT JOIN "State"            s   ON s."StateID"            = u."StateID"
LEFT JOIN "Employee"         e   ON e."EmployeeID"         = cm."PolicePersonID";

