-- =============================================================================
-- DRISHTI migration 007 — canonical identity, case workflow, statements,
--                          property/seizure, digital, and court/outcome domains
-- Target: PostgreSQL 15+ / Supabase (live PG 17.6)
-- Depends on: 005_security_rls_audit.sql, 006_ingestion_evidence.sql
-- =============================================================================
--
-- This is the heart of the identity redesign the audit demanded. It replaces
-- A1/A2/name-based identity with a STABLE CanonicalPersonID reused across cases,
-- a CasePartyRole row per appearance, category-specific append-only CaseEvents,
-- and canonical incident coordinates in CaseVersion (so the spatial-containment
-- gate validates canonical geometry, not the legacy CaseMaster lat/long).
--
-- Legacy tables are preserved. Backward-compatible CanonicalPersonID /
-- CanonicalEntityID / SourceRecordID columns are ADDED (never dropped) so the
-- generator and future readers can migrate off name-joins incrementally.
--
-- RLS stays DISABLED + NO FORCE (hackathon). No RLS policies. Additive +
-- idempotent: safe to run repeatedly.
-- =============================================================================

BEGIN;

-- =============================================================================
-- 1. CANONICAL IDENTITY (Group 3)
-- =============================================================================

CREATE TABLE IF NOT EXISTS "CanonicalPerson" (
    "CanonicalPersonID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicRef"         VARCHAR NOT NULL UNIQUE,     -- e.g. SYN-PERSON-000123 (unmistakably synthetic)
    "DisplayLabel"      VARCHAR,                       -- a LABEL/attribute, never an identity key
    "IsUnknown"         BOOLEAN NOT NULL DEFAULT FALSE,-- unidentified party; no invented identity
    "PrimaryGenderID"   INTEGER,                       -- 1/2/3/NULL (unknown/undisclosed allowed)
    "ApproxBirthYear"   INTEGER,
    "IsJuvenile"        BOOLEAN NOT NULL DEFAULT FALSE,-- protected attribute; excluded from feature schemas
    "ResolutionStatus"  VARCHAR NOT NULL DEFAULT 'canonical', -- canonical|candidate|merged
    "MergedIntoCanonicalPersonID" BIGINT REFERENCES "CanonicalPerson" ("CanonicalPersonID"),
    "Attributes"        JSONB NOT NULL DEFAULT '{}'::jsonb,
    "IsSynthetic"       BOOLEAN NOT NULL DEFAULT TRUE,
    "CreatedAt"         TIMESTAMPTZ NOT NULL DEFAULT now(),
    "UpdatedAt"         TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT "chk_canonperson_resolution"
        CHECK ("ResolutionStatus" IN ('canonical','candidate','merged'))
);
COMMENT ON TABLE "CanonicalPerson" IS 'Stable synthetic person identity reused across cases. Replaces A1/A2/name matching. Names are attributes/aliases, never keys.';

CREATE TABLE IF NOT EXISTS "CanonicalOrganisation" (
    "CanonicalOrganisationID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "PublicRef"   VARCHAR NOT NULL UNIQUE,             -- SYN-ORG-000045
    "Name"        VARCHAR NOT NULL,
    "OrgType"     VARCHAR,                              -- gang|company|association|unknown
    "Attributes"  JSONB NOT NULL DEFAULT '{}'::jsonb,
    "IsSynthetic" BOOLEAN NOT NULL DEFAULT TRUE,
    "CreatedAt"   TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE "CanonicalOrganisation" IS 'Stable synthetic organisation identity (gangs/companies) reused across cases.';

CREATE TABLE IF NOT EXISTS "CanonicalEntity" (
    "CanonicalEntityID"       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "EntityKind"              VARCHAR NOT NULL,        -- person|organisation|phone|vehicle|account|device|location
    "CanonicalPersonID"       BIGINT REFERENCES "CanonicalPerson" ("CanonicalPersonID"),
    "CanonicalOrganisationID" BIGINT REFERENCES "CanonicalOrganisation" ("CanonicalOrganisationID"),
    "PublicRef"   VARCHAR NOT NULL UNIQUE,             -- SYN-ENT-000777
    "Label"       VARCHAR,
    "Attributes"  JSONB NOT NULL DEFAULT '{}'::jsonb,
    "IsSynthetic" BOOLEAN NOT NULL DEFAULT TRUE,
    "CreatedAt"   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT "chk_canonentity_kind" CHECK ("EntityKind" IN
        ('person','organisation','phone','vehicle','account','device','location'))
);
COMMENT ON TABLE "CanonicalEntity" IS 'Unified graph-entity node. EntityGraph links here through CanonicalEntityID (true FK), never through names/array indexes.';

CREATE TABLE IF NOT EXISTS "PersonAlias" (
    "PersonAliasID"     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CanonicalPersonID" BIGINT NOT NULL REFERENCES "CanonicalPerson" ("CanonicalPersonID") ON DELETE CASCADE,
    "AliasName"         VARCHAR NOT NULL,
    "AliasType"         VARCHAR NOT NULL DEFAULT 'alias',  -- alias|aka|nickname|maiden|misspelling
    "SourceRecordID"    BIGINT REFERENCES "SourceRecord" ("SourceRecordID"),
    "IsSynthetic"       BOOLEAN NOT NULL DEFAULT TRUE,
    "CreatedAt"         TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE "PersonAlias" IS 'Alternate names for a canonical person (same-person/alias scenarios). Names are attributes, never identity keys.';

CREATE TABLE IF NOT EXISTS "PersonIdentifier" (
    "PersonIdentifierID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CanonicalPersonID"  BIGINT NOT NULL REFERENCES "CanonicalPerson" ("CanonicalPersonID") ON DELETE CASCADE,
    "IdentifierType"     VARCHAR NOT NULL,     -- synthetic_govt_id|synthetic_pan|synthetic_voter (all clearly fake)
    "IdentifierValue"    VARCHAR NOT NULL,     -- unmistakably synthetic token
    "Sensitivity"        VARCHAR NOT NULL DEFAULT 'restricted',
    "SourceRecordID"     BIGINT REFERENCES "SourceRecord" ("SourceRecordID"),
    "IsSynthetic"        BOOLEAN NOT NULL DEFAULT TRUE,
    "CreatedAt"          TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE "PersonIdentifier" IS 'Synthetic person identifiers (never real IDs). Sensitivity-classified; excluded from model feature schemas by default.';

CREATE TABLE IF NOT EXISTS "PersonContact" (
    "PersonContactID"   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CanonicalPersonID" BIGINT NOT NULL REFERENCES "CanonicalPerson" ("CanonicalPersonID") ON DELETE CASCADE,
    "ContactType"       VARCHAR NOT NULL DEFAULT 'phone',  -- phone|email
    "ContactValue"      VARCHAR NOT NULL,                    -- synthetic phone/email
    "Sensitivity"       VARCHAR NOT NULL DEFAULT 'restricted',
    "SourceRecordID"    BIGINT REFERENCES "SourceRecord" ("SourceRecordID"),
    "IsSynthetic"       BOOLEAN NOT NULL DEFAULT TRUE,
    "CreatedAt"         TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE "PersonContact" IS 'Synthetic contact points for a canonical person. Phone strings are attributes here, never identity keys.';

CREATE TABLE IF NOT EXISTS "PersonAddress" (
    "PersonAddressID"   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CanonicalPersonID" BIGINT NOT NULL REFERENCES "CanonicalPerson" ("CanonicalPersonID") ON DELETE CASCADE,
    "DistrictID"        INTEGER REFERENCES "District" ("DistrictID"),
    "AddressText"       VARCHAR,
    "geom"              geometry(Point, 4326),
    "Sensitivity"       VARCHAR NOT NULL DEFAULT 'restricted',
    "SourceRecordID"    BIGINT REFERENCES "SourceRecord" ("SourceRecordID"),
    "IsSynthetic"       BOOLEAN NOT NULL DEFAULT TRUE,
    "CreatedAt"         TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE "PersonAddress" IS 'Synthetic addresses for a canonical person (district-scoped, on real KA land).';

CREATE TABLE IF NOT EXISTS "EntityResolutionCandidate" (
    "EntityResolutionCandidateID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CanonicalPersonA" BIGINT NOT NULL REFERENCES "CanonicalPerson" ("CanonicalPersonID"),
    "CanonicalPersonB" BIGINT NOT NULL REFERENCES "CanonicalPerson" ("CanonicalPersonID"),
    "Method"           VARCHAR NOT NULL DEFAULT 'deterministic',  -- deterministic|fuzzy
    "Score"            NUMERIC(6,5) CHECK ("Score" IS NULL OR "Score" BETWEEN 0 AND 1),
    "MatchFeatures"    JSONB NOT NULL DEFAULT '{}'::jsonb,
    "Status"           VARCHAR NOT NULL DEFAULT 'pending',  -- pending|accepted|rejected|new
    "ReviewedByActor"  VARCHAR,
    "ReviewedAt"       TIMESTAMPTZ,
    "CreatedAt"        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT "chk_erc_order" CHECK ("CanonicalPersonA" <> "CanonicalPersonB"),
    CONSTRAINT "chk_erc_status" CHECK ("Status" IN ('pending','accepted','rejected','new'))
);
COMMENT ON TABLE "EntityResolutionCandidate" IS 'Proposed person matches for human review. NEVER auto-merged. Same-name/different-person stays separate unless reviewed.';

CREATE TABLE IF NOT EXISTS "EntityMergeHistory" (
    "EntityMergeHistoryID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "Action"          VARCHAR NOT NULL DEFAULT 'merge',   -- merge|split
    "WinnerCanonicalPersonID" BIGINT REFERENCES "CanonicalPerson" ("CanonicalPersonID"),
    "LoserCanonicalPersonID"  BIGINT REFERENCES "CanonicalPerson" ("CanonicalPersonID"),
    "Reason"      TEXT,
    "Actor"       VARCHAR,
    "BeforeState" JSONB NOT NULL DEFAULT '{}'::jsonb,
    "AfterState"  JSONB NOT NULL DEFAULT '{}'::jsonb,
    "CreatedAt"   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT "chk_emh_action" CHECK ("Action" IN ('merge','split'))
);
COMMENT ON TABLE "EntityMergeHistory" IS 'Reversible merge/split decisions with reviewer + before/after state for audit.';

-- =============================================================================
-- 2. CASE-PARTY ROLES (Group 3) — one row per appearance/role
-- =============================================================================
CREATE TABLE IF NOT EXISTS "CasePartyRole" (
    "CasePartyRoleID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CaseMasterID"    INTEGER NOT NULL REFERENCES "CaseMaster" ("CaseMasterID"),
    "CanonicalPersonID" BIGINT REFERENCES "CanonicalPerson" ("CanonicalPersonID"),
    "CanonicalOrganisationID" BIGINT REFERENCES "CanonicalOrganisation" ("CanonicalOrganisationID"),
    "RoleType"        VARCHAR NOT NULL,   -- accused|victim|complainant|witness|informant|guardian|organisation|unknown
    "IsUnknownParty"  BOOLEAN NOT NULL DEFAULT FALSE,
    "LegacyRefTable"  VARCHAR,             -- Accused|Victim|ComplainantDetails (back-compat)
    "LegacyRefID"     INTEGER,             -- the legacy row's PK
    "PartyLabel"      VARCHAR,             -- display name snapshot
    "SequenceNo"      INTEGER,             -- A1/A2 ordering preserved as an attribute, not identity
    "Provenance"      JSONB NOT NULL DEFAULT '{}'::jsonb,
    "CreatedAt"       TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT "chk_casepartyrole_type" CHECK ("RoleType" IN
        ('accused','victim','complainant','witness','informant','guardian','organisation','unknown')),
    CONSTRAINT "chk_casepartyrole_ref" CHECK (
        "CanonicalPersonID" IS NOT NULL
        OR "CanonicalOrganisationID" IS NOT NULL
        OR "IsUnknownParty" = TRUE
    )
);
COMMENT ON TABLE "CasePartyRole" IS 'Links a canonical person/organisation (or an explicit unknown party) to a case with a role. The identity backbone replacing name joins.';

-- =============================================================================
-- 3. CASE SOURCE / VERSION / EVENT + WORKFLOW METADATA (Group 4)
-- =============================================================================
CREATE TABLE IF NOT EXISTS "CaseSource" (
    "CaseSourceID"   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CaseMasterID"   INTEGER NOT NULL REFERENCES "CaseMaster" ("CaseMasterID"),
    "SourceSystemID" INTEGER REFERENCES "SourceSystem" ("SourceSystemID"),
    "SourceRecordID" BIGINT REFERENCES "SourceRecord" ("SourceRecordID"),
    "ExternalRef"    VARCHAR,
    "IngestionMethod" VARCHAR,
    "CreatedAt"      TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE "CaseSource" IS 'Provenance of a case: which source system/record it originated from.';

CREATE TABLE IF NOT EXISTS "CaseVersion" (
    "CaseVersionID"    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CaseMasterID"     INTEGER NOT NULL REFERENCES "CaseMaster" ("CaseMasterID"),
    "VersionNo"        INTEGER NOT NULL DEFAULT 1,
    "CaseCategoryCode" VARCHAR NOT NULL,        -- FIR|UDR|Zero FIR|PAR|NCR|Missing Person
    "StatusCode"       VARCHAR NOT NULL,        -- derived from events / validated
    "IsCurrent"        BOOLEAN NOT NULL DEFAULT TRUE,
    "IncidentLatitude"  NUMERIC(9,6) CHECK ("IncidentLatitude"  IS NULL OR "IncidentLatitude"  BETWEEN -90  AND 90),
    "IncidentLongitude" NUMERIC(9,6) CHECK ("IncidentLongitude" IS NULL OR "IncidentLongitude" BETWEEN -180 AND 180),
    "AssignedDistrictID" INTEGER REFERENCES "District" ("DistrictID"),
    "AssignedUnitID"     INTEGER REFERENCES "Unit" ("UnitID"),
    "geom" geometry(Point, 4326) GENERATED ALWAYS AS (
        CASE WHEN "IncidentLongitude" IS NOT NULL AND "IncidentLatitude" IS NOT NULL
             THEN ST_SetSRID(ST_MakePoint("IncidentLongitude", "IncidentLatitude"), 4326) END
    ) STORED,
    "SnapshotAttributes" JSONB NOT NULL DEFAULT '{}'::jsonb,
    "ChangeReason"     TEXT,
    "Actor"            VARCHAR,
    "ValidFrom"        TIMESTAMPTZ NOT NULL DEFAULT now(),
    "CreatedAt"        TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT "uq_caseversion" UNIQUE ("CaseMasterID", "VersionNo")
);
COMMENT ON TABLE "CaseVersion" IS 'Versioned canonical case snapshot incl. canonical incident coordinates (the spatial-containment source of truth). One IsCurrent per case.';

CREATE UNIQUE INDEX IF NOT EXISTS "uq_caseversion_current"
    ON "CaseVersion" ("CaseMasterID") WHERE "IsCurrent";

CREATE TABLE IF NOT EXISTS "CaseEvent" (
    "CaseEventID"   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CaseMasterID"  INTEGER NOT NULL REFERENCES "CaseMaster" ("CaseMasterID"),
    "EventType"     VARCHAR NOT NULL,     -- registered|transferred|arrest|chargesheet_filed|court_assigned|missing_reported|traced|recovered|inquest|postmortem|converted|reopened|corrected|closed|disposition...
    "EventCategory" VARCHAR,               -- lifecycle|court|evidence|admin
    "SequenceNo"    INTEGER NOT NULL DEFAULT 1,
    "OccurredAt"    TIMESTAMPTZ,
    "RecordedAt"    TIMESTAMPTZ NOT NULL DEFAULT now(),
    "FromStatus"    VARCHAR,
    "ToStatus"      VARCHAR,
    "Payload"       JSONB NOT NULL DEFAULT '{}'::jsonb,
    "ActorRole"     VARCHAR,
    "Provenance"    JSONB NOT NULL DEFAULT '{}'::jsonb,
    "CreatedAt"     TIMESTAMPTZ NOT NULL DEFAULT now()
);
COMMENT ON TABLE "CaseEvent" IS 'Append-only case lifecycle events. Case status is derived from / validated against these, not set arbitrarily.';

CREATE TABLE IF NOT EXISTS "CaseCategoryWorkflow" (
    "CaseCategoryWorkflowID" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CaseCategoryCode" VARCHAR NOT NULL,
    "EventType"        VARCHAR NOT NULL,
    "FromStatus"       VARCHAR,
    "ToStatus"         VARCHAR,
    "RequiresPriorEvent" VARCHAR,        -- prerequisite event type (e.g. chargesheet needs arrest OR investigation)
    "IsTerminal"       BOOLEAN NOT NULL DEFAULT FALSE,
    "Description"      TEXT,
    CONSTRAINT "uq_casecategoryworkflow" UNIQUE ("CaseCategoryCode", "EventType", "FromStatus", "ToStatus")
);
COMMENT ON TABLE "CaseCategoryWorkflow" IS 'Category-specific state-machine transitions AS DATA (seeded by datagen scenario_registry). Not hard-coded if-statements.';

-- =============================================================================
-- 4. EVIDENCE <-> ENTITY LINK (Group 5, needs CanonicalEntity)
-- =============================================================================
CREATE TABLE IF NOT EXISTS "EvidenceEntityLink" (
    "EvidenceEntityLinkID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "EvidenceItemID"    BIGINT NOT NULL REFERENCES "EvidenceItem" ("EvidenceItemID") ON DELETE CASCADE,
    "CanonicalEntityID" BIGINT NOT NULL REFERENCES "CanonicalEntity" ("CanonicalEntityID"),
    "LinkType"      VARCHAR NOT NULL DEFAULT 'mentions',
    "Confidence"    NUMERIC(6,5) CHECK ("Confidence" IS NULL OR "Confidence" BETWEEN 0 AND 1),
    "ReviewStatus"  VARCHAR NOT NULL DEFAULT 'candidate',  -- candidate|reviewed|rejected
    "SourceRecordID" BIGINT REFERENCES "SourceRecord" ("SourceRecordID"),
    "CreatedAt"     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT "uq_evidenceentitylink" UNIQUE ("EvidenceItemID", "CanonicalEntityID", "LinkType")
);
COMMENT ON TABLE "EvidenceEntityLink" IS 'Evidence-to-entity relationships with provenance + review state (feeds provenanced graph edges).';

-- =============================================================================
-- 5. STATEMENTS (Group 6)
-- =============================================================================
CREATE TABLE IF NOT EXISTS "Statement" (
    "StatementID"   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "CaseMasterID"  INTEGER NOT NULL REFERENCES "CaseMaster" ("CaseMasterID"),
    "CanonicalPersonID" BIGINT REFERENCES "CanonicalPerson" ("CanonicalPersonID"),
    "CasePartyRoleID" BIGINT REFERENCES "CasePartyRole" ("CasePartyRoleID"),
    "StatementType" VARCHAR NOT NULL DEFAULT 'witness',   -- witness|complainant|accused|expert
    "RecordedByActor" VARCHAR,
    "RecordedAt"    TIMESTAMPTZ,
    "Place"         VARCHAR,
    "Language"      VARCHAR DEFAULT 'en',
    "AccessClassification" VARCHAR NOT NULL DEFAULT 'demo_normal',  -- demo_normal|restricted
    "State"         VARCHAR NOT NULL DEFAULT 'recorded',  -- draft|recorded|reviewed
    "EvidenceItemID" BIGINT REFERENCES "EvidenceItem" ("EvidenceItemID"),
    "CreatedAt"     TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT "chk_statement_state" CHECK ("State" IN ('draft','recorded','reviewed'))
);
COMMENT ON TABLE "Statement" IS 'Typed statements/interviews. Speaker links to canonical person + case role. Manual entry only (no auto-transcription in hackathon).';

CREATE TABLE IF NOT EXISTS "StatementVersion" (
    "StatementVersionID" BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "StatementID"    BIGINT NOT NULL REFERENCES "Statement" ("StatementID") ON DELETE CASCADE,
