    "CorrectionReason" TEXT,
    "Translation"    TEXT,
    "Redacted"       BOOLEAN NOT NULL DEFAULT FALSE,
    "CreatedByActor" VARCHAR,
    "CreatedAt"      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT "uq_statementversion" UNIQUE ("StatementID", "VersionNo")
);
COMMENT ON TABLE "StatementVersion" IS 'Append-only statement version history (correction/translation/redaction).';

