CREATE INDEX IF NOT EXISTS "idx_intakeparty_draft"      ON "IntakeDraftParty" ("IntakeDraftID");
CREATE INDEX IF NOT EXISTS "idx_intakeparty_person"     ON "IntakeDraftParty" ("CanonicalPersonID");
CREATE INDEX IF NOT EXISTS "idx_intakeparty_role"       ON "IntakeDraftParty" ("RoleType");
CREATE INDEX IF NOT EXISTS "idx_intakeactivity_draft"   ON "IntakeDraftActivity" ("IntakeDraftID");
CREATE INDEX IF NOT EXISTS "idx_intakeactivity_type"    ON "IntakeDraftActivity" ("EventType");

-- =============================================================================
-- 6. TRIGGERS — updated_at maintenance (reuse shared fn_set_updated_at()).
-- =============================================================================
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'trg_intakedraft_updated') THEN
        CREATE TRIGGER "trg_intakedraft_updated" BEFORE UPDATE ON "IntakeDraft"
            FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();
    END IF;
    IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname = 'trg_intakeparty_updated') THEN
        CREATE TRIGGER "trg_intakeparty_updated" BEFORE UPDATE ON "IntakeDraftParty"
            FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();
    END IF;
END$$;

-- =============================================================================
-- 7. VIEW — intake inbox read model (drafts + party counts, no PII expansion).
-- =============================================================================
CREATE OR REPLACE VIEW "vw_intake_inbox" AS
SELECT
    d."IntakeDraftID",
    d."DraftKey",
    d."CaseKind",
    d."CaseCategoryCode",
    d."Status",
    d."CaseMasterID",
    cm."CrimeNo",
    d."CreatedByActor",
    d."SubmittedByActor",
    d."ReviewedByActor",
    d."RevisionNo",
    (SELECT COUNT(*) FROM "IntakeDraftParty" p WHERE p."IntakeDraftID" = d."IntakeDraftID") AS "PartyCount",
    (d."ValidationState" ->> 'ok')::boolean AS "ValidationOk",
    d."CreatedAt",
    d."UpdatedAt",
    d."SubmittedAt",
    d."ReviewedAt"
FROM "IntakeDraft" d
LEFT JOIN "CaseMaster" cm ON cm."CaseMasterID" = d."CaseMasterID";
COMMENT ON VIEW "vw_intake_inbox" IS 'Intake inbox read model: drafts with party counts + validation flag. No narrative/PII expansion.';

